import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const unicodeVersion = '17.0.0'
const sourceUrl = `https://www.unicode.org/Public/${unicodeVersion}/idna/Idna2008.txt`
const dirname = path.dirname(fileURLToPath(import.meta.url))
const outputPath = path.resolve(dirname, '../src/lib/idna2008-ranges.ts')

const response = await fetch(sourceUrl)
if (!response.ok) {
  throw new Error(`Unable to download IDNA2008 data: HTTP ${response.status}`)
}

const source = await response.text()
if (!source.includes(`# Idna2008-${unicodeVersion}.txt`)) {
  throw new Error(`Unexpected IDNA2008 data version from ${sourceUrl}`)
}

const ranges = []
for (const line of source.split(/\r?\n/u)) {
  const match = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(PVALID|CONTEXTJ|CONTEXTO)\b/u)
  if (!match) continue

  const start = Number.parseInt(match[1], 16)
  const end = Number.parseInt(match[2] ?? match[1], 16)
  ranges.push([start, end, match[3]])
}

if (ranges.length < 1_000) {
  throw new Error(`Unexpectedly small IDNA2008 range set: ${ranges.length}`)
}

for (let index = 1; index < ranges.length; index += 1) {
  if (ranges[index - 1][1] >= ranges[index][0]) {
    throw new Error(`Overlapping IDNA2008 ranges at index ${index}`)
  }
}

const sha256 = createHash('sha256').update(source).digest('hex')
const rows = ranges
  .map(
    ([start, end, category]) =>
      `  [0x${start.toString(16)}, 0x${end.toString(16)}, '${category}'],`,
  )
  .join('\n')

const output = `// Generated by scripts/generate-idna2008-ranges.mjs. Do not edit by hand.
// Source: ${sourceUrl}
// Source SHA-256: ${sha256}

export const IDNA2008_UNICODE_VERSION = '${unicodeVersion}'

export type Idna2008Category = 'CONTEXTJ' | 'CONTEXTO' | 'PVALID'
export type Idna2008Range = readonly [start: number, end: number, category: Idna2008Category]

export const IDNA2008_ALLOWED_RANGES: readonly Idna2008Range[] = [
${rows}
]
`

await writeFile(outputPath, output, 'utf8')
console.log(`Generated ${ranges.length} IDNA2008 ranges for Unicode ${unicodeVersion}`)
